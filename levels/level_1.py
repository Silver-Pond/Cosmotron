    # DRAW ALL VISIBLE WALLS
    def draw_walls(self, visible_rows):

        half_w = self.wall_width / 2
        half_h = self.wall_height / 2
        half_d = self.wall_depth / 2

        wall_y = self.floor_y + half_h

        # Face definitions
        faces = (
            (0, 1, 2, 3),
            (4, 5, 6, 7),
            (0, 4, 7, 3),
            (1, 5, 6, 2),
            (0, 1, 5, 4),
            (3, 2, 6, 7)
        )

        tex_coords = (
            (0.0, 0.0),
            (1.0, 0.0),
            (1.0, 1.0),
            (0.0, 1.0)
        )

        glEnable(GL_TEXTURE_2D)

        glBindTexture(GL_TEXTURE_2D, self.wall_texture)

        glColor3f(1.0, 1.0, 1.0)

        # One batch for every visible wall
        glBegin(GL_QUADS)

        for row in visible_rows:

            z = self.z_positions[row]

            for column, tile in enumerate(self.map[row]):

                if tile != 1:
                    continue

                x = self.x_positions[column]

                # Cube vertices
                vertices = (
                    (x - half_w, wall_y - half_h, z - half_d),
                    (x + half_w, wall_y - half_h, z - half_d),
                    (x + half_w, wall_y + half_h, z - half_d),
                    (x - half_w, wall_y + half_h, z - half_d),

                    (x - half_w, wall_y - half_h, z + half_d),
                    (x + half_w, wall_y - half_h, z + half_d),
                    (x + half_w, wall_y + half_h, z + half_d),
                    (x - half_w, wall_y + half_h, z + half_d)
                )

                for face in faces:

                    for i, vertex_index in enumerate(face):
                        glTexCoord2f(*tex_coords[i])

                        glVertex3fv(vertices[vertex_index])

        glEnd()

        glBindTexture(GL_TEXTURE_2D, 0)

        glDisable(GL_TEXTURE_2D)

    # DRAW DESTRUCTIBLE WALLS
    def draw_destructible_walls(self, visible_rows):

        half_w = self.wall_width / 2
        half_h = self.wall_height / 2
        half_d = self.wall_depth / 2

        wall_y = self.floor_y + half_h

        faces = (
            (0, 1, 2, 3),
            (4, 5, 6, 7),
            (0, 4, 7, 3),
            (1, 5, 6, 2),
            (0, 1, 5, 4),
            (3, 2, 6, 7)
        )

        tex_coords = (
            (0.0, 0.0),
            (1.0, 0.0),
            (1.0, 1.0),
            (0.0, 1.0)
        )

        glEnable(GL_TEXTURE_2D)
        glBindTexture(GL_TEXTURE_2D, self.breakable_wall_texture)

        # Give destructible walls a no tint
        glColor3f(1.0, 1.0, 1.0)

        glBegin(GL_QUADS)

        for row, column in self.destructible_walls:

            if row not in visible_rows:
                continue

            x = self.x_positions[column]
            z = self.z_positions[row]

            vertices = (
                (x - half_w, wall_y - half_h, z - half_d),
                (x + half_w, wall_y - half_h, z - half_d),
                (x + half_w, wall_y + half_h, z - half_d),
                (x - half_w, wall_y + half_h, z - half_d),

                (x - half_w, wall_y - half_h, z + half_d),
                (x + half_w, wall_y - half_h, z + half_d),
                (x + half_w, wall_y + half_h, z + half_d),
                (x - half_w, wall_y + half_h, z + half_d)
            )

            for face in faces:

                for i, vertex_index in enumerate(face):
                    glTexCoord2f(*tex_coords[i])
                    glVertex3fv(vertices[vertex_index])

        glEnd()

        glBindTexture(GL_TEXTURE_2D, 0)
        glDisable(GL_TEXTURE_2D)

        # Restore normal wall color
        glColor3f(1.0, 1.0, 1.0)

    # DRAW VISIBLE MAP
    def draw(self):

        glDisable(GL_TEXTURE_2D)
        glDisable(GL_LIGHTING)

        # Calculate visible rows once
        visible_rows = self.get_visible_rows()

        # Draw floor in one batch
        self.draw_floor(visible_rows)

        # Draw walls in one batch
        self.draw_walls(visible_rows)

        # Draw destructible walls
        self.draw_destructible_walls(visible_rows)

        # Draw visible enemies
        self.draw_tesseracts(visible_rows)

        # Draw visible black holes
        self.draw_black_holes(visible_rows)

        # Draw portal if visible
        if self.portal is not None:

            portal_row = round(
                self.portal.z / self.cell_size
                + (self.rows - 1) / 2
            )

            if portal_row in visible_rows:
                self.portal.draw()

    # Get Wall Positions
    def get_wall_positions(self):

        walls = []

        for row in range(self.rows):

            for column in range(self.columns):

                if self.map[row][column] == 1:
                    x = (column - (self.columns - 1) / 2) * self.cell_size
                    z = (row - (self.rows - 1) / 2) * self.cell_size

                    walls.append((x, z))

        return walls

    # UPDATE TESSERACTS
    def update_tesseracts(self, delta_time):

        for enemy in self.tesseracts:
            enemy.update(delta_time)

    # DRAW VISIBLE TESSERACTS
    def draw_tesseracts(self, visible_rows=None):

        if visible_rows is None:
            visible_rows = self.get_visible_rows()

        start_row = visible_rows.start
        end_row = visible_rows.stop

        for enemy in self.tesseracts:

            enemy_row = round(
                enemy.z / self.cell_size
                + (self.rows - 1) / 2
            )

            if start_row <= enemy_row < end_row:
                enemy.draw()

    # UPDATE BLACK HOLES
    def update_black_holes(self, delta_time):

        for black_hole in self.black_holes:
            black_hole.update(delta_time)

    # DRAW VISIBLE BLACK HOLES
    def draw_black_holes(self, visible_rows=None):

        if visible_rows is None:
            visible_rows = self.get_visible_rows()

        start_row = visible_rows.start
        end_row = visible_rows.stop

        for black_hole in self.black_holes:

            black_hole_row = round(
                black_hole.z / self.cell_size
                + (self.rows - 1) / 2
            )

            if start_row <= black_hole_row < end_row:
                black_hole.draw()

    # WALL COLLISION DETECTION
    def collides_with_wall(self, x, z, player_radius):

        half_wall = self.cell_size / 2
        radius_squared = player_radius ** 2

        center_column = round(x / self.cell_size + (self.columns - 1) / 2)
        center_row = round(z / self.cell_size + (self.rows - 1) / 2)

        reach = int(player_radius / self.cell_size) + 1

        min_column = max(0, center_column - reach)
        max_column = min(self.columns - 1, center_column + reach)

        min_row = max(0, center_row - reach)
        max_row = min(self.rows - 1, center_row + reach)

        for row in range(min_row, max_row + 1):

            for column in range(min_column, max_column + 1):

                # Check both normal and destructible walls
                if (row, column) not in self.wall_cells and (row, column) not in self.destructible_walls:
                    continue

                wall_x = self.x_positions[column]
                wall_z = self.z_positions[row]

                # Closest point on the wall
                closest_x = max(
                    wall_x - half_wall,
                    min(x, wall_x + half_wall)
                )

                closest_z = max(
                    wall_z - half_wall,
                    min(z, wall_z + half_wall)
                )

                dx = x - closest_x
                dz = z - closest_z

                if dx * dx + dz * dz < radius_squared:
                    return True

        return False

    def check_destructible_wall_collision(self, x, z, bullet_radius):

        half_wall = self.cell_size / 2

        center_column = round(
            x / self.cell_size + (self.columns - 1) / 2
        )

        center_row = round(
            z / self.cell_size + (self.rows - 1) / 2
        )

        reach = int(bullet_radius / self.cell_size) + 1

        min_column = max(0, center_column - reach)
        max_column = min(self.columns - 1, center_column + reach)

        min_row = max(0, center_row - reach)
        max_row = min(self.rows - 1, center_row + reach)

        for row in range(min_row, max_row + 1):

            for column in range(min_column, max_column + 1):

                if (row, column) not in self.destructible_walls:
                    continue

                wall_x = self.x_positions[column]
                wall_z = self.z_positions[row]

                closest_x = max(
                    wall_x - half_wall,
                    min(x, wall_x + half_wall)
                )

                closest_z = max(
                    wall_z - half_wall,
                    min(z, wall_z + half_wall)
                )

                dx = x - closest_x
                dz = z - closest_z

                if dx * dx + dz * dz <= bullet_radius ** 2:
                    # Remove the destructible wall
                    self.destructible_walls.remove((row, column))
                    self.map[row][column] = 0

                    print(
                        f"DESTRUCTIBLE WALL DESTROYED: "
                        f"row={row}, column={column}"
                    )

                    return True

        return False

    # CHECK PORTAL COLLISION
    def check_portal_collision(self, player):
        if self.portal is None:
            return False

        return self.portal.check_collision(player)

    # CHECK BULLET COLLISION WITH DESTRUCTIBLE WALLS
    def check_bullet_wall_collision(self, player):

        remaining_bullets = []

        half_wall = self.cell_size / 2
        bullet_radius = getattr(player, "bullet_collision_radius", 0.15)

        for bullet in player.bullets:

            # Previous and current bullet positions
            start_x = bullet.get("prev_x", bullet["x"])
            start_y = bullet.get("prev_y", bullet["y"])
            start_z = bullet.get("prev_z", bullet["z"])

            end_x = bullet["x"]
            end_y = bullet["y"]
            end_z = bullet["z"]

            hit_wall = False

            for row, column in list(self.destructible_walls):

                wall_x = self.x_positions[column]
                wall_z = self.z_positions[row]

                # Wall boundaries, expanded by bullet radius
                min_x = wall_x - half_wall - bullet_radius
                max_x = wall_x + half_wall + bullet_radius

                min_y = self.floor_y - bullet_radius
                max_y = self.floor_y + self.wall_height + bullet_radius

                min_z = wall_z - half_wall - bullet_radius
                max_z = wall_z + half_wall + bullet_radius

                # Segment intersection test
                t_min = 0.0
                t_max = 1.0

                start = (start_x, start_y, start_z)
                end = (end_x, end_y, end_z)

                bounds = (
                    (min_x, max_x),
                    (min_y, max_y),
                    (min_z, max_z)
                )

                for axis in range(3):

                    direction = end[axis] - start[axis]

                    if abs(direction) < 0.000001:

                        if not (bounds[axis][0] <= start[axis] <= bounds[axis][1]):
                            t_min = 2.0
                            break

                    else:

                        t1 = (bounds[axis][0] - start[axis]) / direction
                        t2 = (bounds[axis][1] - start[axis]) / direction

                        if t1 > t2:
                            t1, t2 = t2, t1

                        t_min = max(t_min, t1)
                        t_max = min(t_max, t2)

                        if t_min > t_max:
                            break

                if t_min <= t_max:
                    # Destroy the wall
                    self.destructible_walls.remove((row, column))
                    self.map[row][column] = 0

                    hit_wall = True

                    print(f"DESTRUCTIBLE WALL DESTROYED: row={row}, column={column}")

                    break

            # Remove bullets that hit a breakable wall
            if not hit_wall:
                remaining_bullets.append(bullet)

        player.bullets = remaining_bullets

    # Wall collider addition (player movement)
    def move_player(self, player, move_x, move_z):
        """
        Moves the player while preventing horizontal wall penetration.
        Resolves X and Z separately to allow wall sliding.
        """

        # Resolve X movement.
        new_x = player.x + move_x

        if not self.collides_with_wall(new_x, player.z, player.radius):
            player.x = new_x

        # Resolve Z movement.
        new_z = player.z + move_z

        if not self.collides_with_wall(player.x, new_z, player.radius):
            player.z = new_z

    # Timer code
    def update_timer(self, delta_time):
        if self.timer > 0:
            self.timer -= delta_time

        if self.timer <= 0:
            self.timer = 0
            self.time_up = True

    # CLEANUP LEVEL
    def cleanup(self):

        # Clean up black-hole textures
        for black_hole in self.black_holes:
            black_hole.cleanup()

        # Delete wall texture
        if self.wall_texture:
            glDeleteTextures([self.wall_texture])
            self.wall_texture = None

        # Delete destructible wall texture
        if self.breakable_wall_texture:
            glDeleteTextures([self.breakable_wall_texture])
            self.breakable_wall_texture = None

