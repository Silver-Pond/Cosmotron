class LevelMap:

    def __init__(self, level_data = map):

        self.map = level_data

        self.rows = len(self.map)
        self.columns = len(self.map[0])

        # =====================================
        # MAP SETTINGS
        # =====================================

        self.cell_size = 0.4

        self.floor_y = -2.8

        self.wall_height = 0.7
        self.wall_depth = self.cell_size

        self.floor_colour = (0.25, 0.035, 0.09)

        # =====================================
        # DYNAMIC MAP LOADING SETTINGS
        # =====================================

        # Number of rows rendered ahead of player
        self.render_distance_ahead = 40

        # Number of rows rendered behind player
        self.render_distance_behind = 4

        # Current player position
        self.player_z = 0.0

        # Cache wall positions
        self.wall_positions = self.get_wall_positions()

    # =====================================
    # UPDATE PLAYER POSITION
    # =====================================

    def update(self, player_z):
        self.player_z = player_z

    # =====================================
    # GET PLAYER MAP ROW
    # =====================================

    def get_player_row(self):

        row = int(
            round(
                self.player_z / self.cell_size
                + (self.rows - 1) / 2
            )
        )

        return max(0, min(self.rows - 1, row))

    # =====================================
    # GET VISIBLE MAP ROWS
    # =====================================

    def get_visible_rows(self):

        player_row = self.get_player_row()

        start_row = max(0, player_row - self.render_distance_ahead)
        end_row = min(self.rows, player_row + self.render_distance_behind + 1)

        return range(start_row, end_row)

    # =====================================
    # DRAW FLOOR TILE
    # =====================================

    def draw_floor_tile(self, x, z):

        half = self.cell_size / 2

        y = self.floor_y

        glColor3f(*self.floor_colour)

        glBegin(GL_QUADS)

        glVertex3f(x-half, y, z-half)
        glVertex3f(x+half, y, z-half)
        glVertex3f(x+half, y, z+half)
        glVertex3f(x-half, y, z+half)

        glEnd()

    # =====================================
    # DRAW WALL CUBE
    # =====================================

    def draw_cube(self, x, y, z):

        half = self.cell_size / 2
        height = self.wall_height / 2
        depth = self.wall_depth / 2

        vertices = [
            (x-half, y-height, z-depth),
            (x+half, y-height, z-depth),
            (x+half, y+height, z-depth),
            (x-half, y+height, z-depth),

            (x-half, y-height, z+depth),
            (x+half, y-height, z+depth),
            (x+half, y+height, z+depth),
            (x-half, y+height, z+depth)
        ]

        faces = [
            (0, 1, 2, 3),
            (4, 5, 6, 7),
            (0, 4, 7, 3),
            (1, 5, 6, 2),
            (0, 1, 5, 4),
            (3, 2, 6, 7)
        ]

        colours = [
            (0.12, 0.16, 0.28),
            (0.20, 0.25, 0.40),
            (0.08, 0.11, 0.20),
            (0.15, 0.20, 0.32),
            (0.06, 0.09, 0.16),
            (0.25, 0.30, 0.45)
        ]

        glBegin(GL_QUADS)

        for i, face in enumerate(faces):

            glColor3fv(colours[i])

            for vertex in face:
                glVertex3fv(vertices[vertex])

        glEnd()

    # =====================================
    # DRAW VISIBLE MAP
    # =====================================

    def draw(self):

        glDisable(GL_TEXTURE_2D)
        glDisable(GL_LIGHTING)

        # Only render selected map rows
        visible_rows = self.get_visible_rows()

        for row in visible_rows:

            for column in range(self.columns):

                x = (column - (self.columns - 1) / 2) * self.cell_size
                z = (row - (self.rows - 1) / 2) * self.cell_size

                # Draw floor
                self.draw_floor_tile(x, z)

                # Draw wall if tile contains a wall
                if self.map[row][column] == 1:
                    self.draw_cube(x, self.floor_y + self.wall_height / 2, z)

    # =====================================
    # GET WALL POSITIONS
    # =====================================

    def get_wall_positions(self):

        walls = []

        for row in range(self.rows):

            for column in range(self.columns):

                if self.map[row][column] == 1:

                    x = (
                        column - (self.columns - 1) / 2
                    ) * self.cell_size

                    z = (
                        row - (self.rows - 1) / 2
                    ) * self.cell_size

                    walls.append((x, z))

        return walls

