class LevelMap:

    def __init__(self, level_data = None):

        self.map = level_data if level_data is not None else map

        if not self.map:
            raise ValueError("Level map cannot be empty.")

        self.rows = len(self.map)
        self.columns = len(self.map[0])

        # Validate map dimensions
        if any(len(row) != self.columns for row in self.map):
            raise ValueError("All map rows must have the same number of columns.")

        # Validate map tile values
        valid_tiles = {0, 1, 2, 3, 4, 5, 6}

        if any(tile not in valid_tiles for row in self.map for tile in row):
            raise ValueError("Level map contains an invalid tile value.")

        # MAP SETTINGS
        self.cell_size = 1.28
        self.floor_y = -2.8

        self.timer = 60.0
        self.time_up = False

        self.wall_width = self.cell_size
        self.wall_height = self.cell_size
        self.wall_depth = self.cell_size

        self.floor_colour = (0.0, 0.0, 0.0)

        # RENDER DISTANCE
        self.render_distance_ahead = 30
        self.render_distance_behind = 3

        self.player_z = 0.0

        # PRE-CALCULATED MAP COORDINATES
        self.x_positions = [
            (column - (self.columns - 1) / 2) * self.cell_size
            for column in range(self.columns)
        ]

        self.z_positions = [
            (row - (self.rows - 1) / 2) * self.cell_size
            for row in range(self.rows)
        ]

        # CACHE WALL GRID POSITIONS
        self.wall_cells = {
            (row_index, column_index)
            for row_index, row in enumerate(self.map)
            for column_index, tile in enumerate(row)
            if tile == 1
        }

        # CACHE DESTRUCTIBLE WALL POSITIONS
        self.destructible_walls = {
            (row_index, column_index)
            for row_index, row in enumerate(self.map)
            for column_index, tile in enumerate(row)
            if tile == 6
        }

        # LOAD WALL TEXTURES
        self.wall_texture = self.load_wall_texture()
        self.breakable_wall_texture = self.load_breakable_wall_texture()

        # LOAD ENEMIES AND PORTAL
        self.tesseracts = []
        self.portal = None
        self.black_holes = []

        for row_index, row in enumerate(self.map):

            world_z = self.z_positions[row_index]

            for col_index, tile in enumerate(row):

                world_x = self.x_positions[col_index]

                if tile == 2:
                    self.tesseracts.append(Tesseract(world_x, world_z, self))

                elif tile == 3:
                    self.tesseracts.append(PurpleTesseract(world_x, world_z, self))

                elif tile == 4:
                    if self.portal is not None:
                        raise ValueError("A level can only contain one portal.")

                    self.portal = Portal(world_x, world_z, self)

                elif tile == 5:
                    self.black_holes.append(BlackHole(world_x, world_z, self))

        # LOADING INFORMATION
        print(f"Level loaded: {self.rows} rows x {self.columns} columns")
        print(f"Walls loaded: {len(self.wall_cells)}")
        print(f"Tesseracts loaded: {len(self.tesseracts)}")

        if self.portal:
            print(f"Portal loaded: ({self.portal.x}, {self.portal.z})")
        else:
            print("WARNING: No portal found in this level!")

    # UPDATE PLAYER POSITION
    def update(self, player_z):
        self.player_z = player_z

    # UPDATE PORTAL
    def update_portal(self, delta_time):
        if self.portal is not None:
            self.portal.update(delta_time)

    # GET PLAYER MAP ROW
    def get_player_row(self):

        row = int(round(self.player_z / self.cell_size
                + (self.rows - 1) / 2))

        return max(0, min(self.rows - 1, row))

    # GET VISIBLE MAP ROWS
    def get_visible_rows(self):

        player_row = self.get_player_row()

        start_row = max(0, player_row - self.render_distance_ahead)
        end_row = min(self.rows, player_row + self.render_distance_behind + 1)

        return range(start_row, end_row)

    # DRAW ALL VISIBLE FLOOR TILES
    def draw_floor(self, visible_rows):

        half = self.cell_size / 2
        y = self.floor_y

        glColor3f(*self.floor_colour)

        glBegin(GL_QUADS)

        for row in visible_rows:

            z = self.z_positions[row]

            for x in self.x_positions:
                glVertex3f(x - half, y, z - half)
                glVertex3f(x + half, y, z - half)
                glVertex3f(x + half, y, z + half)
                glVertex3f(x - half, y, z + half)

        glEnd()

    # Load Anomaly Texture
    def load_wall_texture(self):

        texture_path = os.path.join("assets/enemies", "anomaly.png")

        image = Image.open(texture_path).convert("RGBA")
        image = image.transpose(Image.FLIP_TOP_BOTTOM)
        image_data = image.tobytes()

        texture = glGenTextures(1)
        glBindTexture(GL_TEXTURE_2D, texture)

        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR)
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR)
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_REPEAT)
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_REPEAT)

        glTexImage2D(
            GL_TEXTURE_2D, 0, GL_RGBA, image.width, image.height,
            0, GL_RGBA, GL_UNSIGNED_BYTE, image_data)

        glBindTexture(GL_TEXTURE_2D, 0)

        return texture

