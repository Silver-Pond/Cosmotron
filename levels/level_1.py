class LevelMap:

    def __init__(self, level_data = map):

        self.map = level_data

        self.rows = len(self.map)
        self.columns = len(self.map[0])

        # Size of each grid cell
        self.cell_size = 0.4

        # Floor height
        self.floor_y = -2.8

        # Wall dimensions
        self.wall_height = 0.7
        self.wall_depth = self.cell_size

        # Arena colours
        self.floor_colour = (0.25, 0.035, 0.09)

        # Cache wall positions
        self.wall_positions = self.get_wall_positions()

    # Draw floor code
    def draw_floor_tile(self, x, z):

        half = self.cell_size / 2

        y = self.floor_y

        glColor3f(*self.floor_colour)

        glBegin(GL_QUADS)

        glVertex3f(x-half, y, z-half)
        glVertex3f(x+half, y, z-half)
        glVertex3f(x+half, y, z+half)
        glVertex3f(x-half, y, z+half)

        glEnd()

    # Draw cube code
    def draw_cube(self, x, y, z):

        half = self.cell_size / 2
        height = self.wall_height / 2
        depth = self.wall_depth / 2

        vertices = [
            (x-half, y-height, z-depth),
            (x+half, y-height, z-depth),
            (x+half, y+height, z-depth),
            (x-half, y+height, z-depth),

            (x-half, y-height, z+depth),
            (x+half, y-height, z+depth),
            (x+half, y+height, z+depth),
            (x-half, y+height, z+depth)
        ]

        faces = [
            (0, 1, 2, 3),
            (4, 5, 6, 7),
            (0, 4, 7, 3),
            (1, 5, 6, 2),
            (0, 1, 5, 4),
            (3, 2, 6, 7)
        ]

        colours = [
            (0.12, 0.16, 0.28),
            (0.20, 0.25, 0.40),
            (0.08, 0.11, 0.20),
            (0.15, 0.20, 0.32),
            (0.06, 0.09, 0.16),
            (0.25, 0.30, 0.45)
        ]

        glBegin(GL_QUADS)

        for i, face in enumerate(faces):

            glColor3fv(colours[i])

            for vertex in face:
                glVertex3fv(vertices[vertex])

        glEnd()

    # Draw map code
    def draw(self):

        glDisable(GL_TEXTURE_2D)
        glDisable(GL_LIGHTING)

        # Draw the floor across the entire XZ plane
        for row in range(self.rows):

            for column in range(self.columns):

                x = (
                    column - (self.columns - 1) / 2
                ) * self.cell_size

                z = (
                    row - (self.rows - 1) / 2
                ) * self.cell_size

                self.draw_floor_tile(x, z)

        # Draw raised walls
        for row in range(self.rows):

            for column in range(self.columns):

                if self.map[row][column] == 1:

                    x = (
                        column - (self.columns - 1) / 2
                    ) * self.cell_size

                    z = (
                        row - (self.rows - 1) / 2
                    ) * self.cell_size

                    self.draw_cube(
                        x,
                        self.floor_y + self.wall_height / 2,
                        z
                    )

    def get_wall_positions(self):

        walls = []

        for row in range(self.rows):

            for column in range(self.columns):

                if self.map[row][column] == 1:

                    x = (
                        column - (self.columns - 1) / 2
                    ) * self.cell_size

                    z = (
                        row - (self.rows - 1) / 2
                    ) * self.cell_size

                    walls.append((x, z))

        return walls

    # WALL COLLISION DETECTION
    def check_wall_collision(self, x, z, radius_x=0.3, radius_z=0.3):

        half_wall = self.cell_size / 2

        # Check every wall
        for wall_x, wall_z in self.wall_positions:

            # Wall boundaries
            wall_min_x = wall_x - half_wall
            wall_max_x = wall_x + half_wall

            wall_min_z = wall_z - half_wall
            wall_max_z = wall_z + half_wall

            # Player boundaries
            player_min_x = x - radius_x
            player_max_x = x + radius_x

            player_min_z = z - radius_z
            player_max_z = z + radius_z

            # Check for overlap
            if (
                    player_max_x > wall_min_x and
                    player_min_x < wall_max_x and
                    player_max_z > wall_min_z and
                    player_min_z < wall_max_z
            ):
                return True

        return False

